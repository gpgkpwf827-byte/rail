#!/usr/bin/env python3
"""Railway Manager v0.5b: provisional NaPTAN RLY to archived Network Rail VectorLinks mapping.

Creates display-only snapped candidates, not a station routing graph or authoritative track assignment.
Only Python standard library is required. Inputs are generated by existing v0.4/v0.5a importers.
"""
import argparse
import collections
import hashlib
import json
import math
from pathlib import Path

# Keep current UI IDs linked to NaPTAN codes without changing the owned hub or replacing live markers.
STARTER_ATCO = {
    'ipswich':'9100IPSWICH', 'needham':'9100NEEDHAM', 'stowmarket':'9100STWMRKT',
    'diss':'9100DISS', 'norwich':'9100NRCH', 'manningtree':'9100MANNGTR',
    'colchester':'9100CLCHSTR', 'derbyroad':'9100DERBYRD',
    'woodbridge':'9100WODBDGE', 'melton':'9100MELTON',
    'saxmundham':'9100SXMNDHM', 'wickham':'9100WCKHMMR',
}
R = 6371008.8

def project(lon, lat, cos_lat):
    return (R * math.radians(lon) * cos_lat, R * math.radians(lat))

def nearest_on_segment(px, py, a, b):
    vx=b[0]-a[0]; vy=b[1]-a[1]
    lensq=vx*vx+vy*vy
    t=max(0.0,min(1.0,((px-a[0])*vx+(py-a[1])*vy)/lensq)) if lensq else 0.0
    x=a[0]+vx*t; y=a[1]+vy*t
    return (px-x)**2+(py-y)**2,t

def lines(geometry):
    if geometry['type']=='LineString':
        yield geometry['coordinates']
    elif geometry['type']=='MultiLineString':
        yield from geometry['coordinates']

def get_edges(track):
    edges=[]
    for fi, feature in enumerate(track['features']):
        for li, line in enumerate(lines(feature['geometry'])):
            for a,b in zip(line,line[1:]):
                if len(a)>=2 and len(b)>=2 and a[:2]!=b[:2]:
                    edges.append((a[:2],b[:2],fi,li))
    return edges

def match_points(stations, track, limit_m=250):
    edges=get_edges(track)
    if not edges: raise ValueError('Track geometry contains no line segments')
    results=[]
    for feat in stations['features']:
        p=feat['properties']; lon,lat=feat['geometry']['coordinates'][:2]
        if not (-180<=lon<=180 and -90<=lat<=90): raise ValueError('Invalid station coordinate')
        coslat=math.cos(math.radians(lat))
        px,py=project(lon,lat,coslat)
        nearest=(math.inf,None,None)
        # Approximate bounding window, deliberately generous for 250m matches.
        lat_margin=max(limit_m,500)/110000
        lon_margin=lat_margin/max(coslat,0.1)
        for a,b,fi,li in edges:
            if not (min(a[0],b[0])-lon_margin<=lon<=max(a[0],b[0])+lon_margin and
                    min(a[1],b[1])-lat_margin<=lat<=max(a[1],b[1])+lat_margin):
                continue
            aa=project(a[0],a[1],coslat); bb=project(b[0],b[1],coslat)
            d2,t=nearest_on_segment(px,py,aa,bb)
            if d2<nearest[0]:
                nearest=(d2,[a[0]+t*(b[0]-a[0]),a[1]+t*(b[1]-a[1])],fi)
        d2,snap,fi=nearest
        dist=round(math.sqrt(d2),1) if snap else None
        # Maximum distance is a hard gate; no automatic relocation for uncertain matches.
        accepted=dist is not None and dist<=limit_m
        visual=snap if accepted else [lon,lat]
        status='review' if dist is None or dist>75 else ('caution' if dist>25 else 'candidate')
        props={**p,'officialCoordinates':[lon,lat],
               'displayMatchStatus': status if accepted else 'unmatched',
               'displayDistanceMetres':dist,
               'displayTrackFeatureIndex':fi if accepted else None,
               'displayTrackELR':track['features'][fi]['properties'].get('ELR') if accepted else None,
               'displayOnly':True,'trackConnectionVerified':False}
        results.append({'type':'Feature','properties':props,'geometry':{'type':'Point','coordinates':[round(v,7) for v in visual]}})
    return results, len(edges)

def main():
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--stations',required=True)
    cli.add_argument('--tracks',required=True)
    cli.add_argument('--output',default='data/derived/stations-east-matched-candidate.geojson')
    cli.add_argument('--report',default='data/derived/stations-east-matching-report.json')
    cli.add_argument('--max-snap-metres',type=float,default=250)
    args=cli.parse_args()
    station_bytes=Path(args.stations).read_bytes(); track_bytes=Path(args.tracks).read_bytes()
    stations=json.loads(station_bytes); track=json.loads(track_bytes)
    if stations.get('type')!='FeatureCollection' or track.get('type')!='FeatureCollection':raise ValueError('Expected GeoJSON FeatureCollections')
    matches, segments=match_points(stations,track,args.max_snap_metres)
    grouped=collections.defaultdict(list)
    for f in matches:
        p=f['properties'];grouped[(p['name'].casefold(),p.get('locality','').casefold())].append(f)
    duplicates=[]
    for (name,loc),features in grouped.items():
        if len(features)>1:
            ids=[f['properties']['atcoCode'] for f in features]
            duplicates.append({'name':name,'locality':loc,'atcoCodes':ids,'action':'manual review before combining; preserve separate source records'})
            for f in features:f['properties']['possibleDuplicate']=True
    atco_to_ui={code:ui for ui,code in STARTER_ATCO.items()}
    for f in matches:
        p=f['properties']
        p['starterUiId']=atco_to_ui.get(p['atcoCode'])
        if 'possibleDuplicate' not in p:p['possibleDuplicate']=False
    missing_starters=[{'uiId':ui,'atcoCode':code} for ui,code in STARTER_ATCO.items() if code not in {f['properties']['atcoCode'] for f in matches}]
    distribution=dict(collections.Counter(f['properties']['displayMatchStatus'] for f in matches))
    review=sorted([{'atcoCode':f['properties']['atcoCode'],'name':f['properties']['name'],'distanceMetres':f['properties']['displayDistanceMetres'],'status':f['properties']['displayMatchStatus']} for f in matches if f['properties']['displayMatchStatus'] in ('review','unmatched')],key=lambda x:(x['distanceMetres'] is None, x['distanceMetres'] or 0),reverse=True)
    distances=sorted(f['properties']['displayDistanceMetres'] for f in matches if f['properties']['displayDistanceMetres'] is not None)
    report={'version':'0.5b','source':'NaPTAN RLY + archived Network Rail VectorLinks',
      'station_input_sha256':hashlib.sha256(station_bytes).hexdigest(),'track_input_sha256':hashlib.sha256(track_bytes).hexdigest(),
      'candidate_station_count':len(matches),'track_segments_checked':segments,'match_status_counts':distribution,
      'median_nearest_track_distance_m':distances[len(distances)//2] if distances else None,
      'maximum_nearest_track_distance_m':distances[-1] if distances else None,
      'needs_review':review,'potential_duplicate_groups':duplicates,
      'starter_atco_mapping':STARTER_ATCO,'starter_missing':missing_starters,
      'warning':'Visual snapping only. Nearest track may be a siding, separate track, or historical alignment. No platform, service, or topological connection is confirmed.'}
    out=Path(args.output);rep=Path(args.report);out.parent.mkdir(parents=True,exist_ok=True);rep.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps({'type':'FeatureCollection','features':matches},ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    rep.write_text(json.dumps(report,indent=2,ensure_ascii=False),encoding='utf-8')
    print(f'Matched {len(matches)} stations to {segments} track segments. Status: {distribution}. Review: {len(review)}. Missing starter mappings: {len(missing_starters)}.')
    print(f'Outputs: {out}, {rep}')
if __name__=='__main__':main()
